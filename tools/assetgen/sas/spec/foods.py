"""Kitchen content: ingredients, dishes, drinks and feasts.

Stations
  * crafting table    - assembly (sandwiches, salads, juices) and vanilla-style baking
  * mortar & pestle   - ``grind``: shapeless crafting that damages the mortar instead of using it up
  * cutting board     - ``cut``: place an ingredient, use a knife
  * cooking pot       - ``pot``: up to 6 ingredients + optional serving container, needs heat below
  * furnace/smoker/campfire - ``cook``
"""
