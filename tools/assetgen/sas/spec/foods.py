def well_fed(seconds, amp=0):
    return Effect("sprout_and_soil:well_fed", seconds, amp)


def cozy(seconds, amp=0):
    return Effect("sprout_and_soil:cozy", seconds, amp)


def caffeinated(seconds, amp=0):
    return Effect("sprout_and_soil:caffeinated", seconds, amp)


def ingredient(id_, recipes, art, food=None, remainder=None, container=None, tags=(), name=None,
               compost=None, stack=64, tooltip=None, category="ingredient"):
    return ItemDef(id=id_, name=name, food=food, recipes=list(recipes), art=art, remainder=remainder,
                   container=container, tags=list(tags), compost=compost, stack=stack, tab="kitchen",
                   category=category, tooltip=tooltip is not None, desc=tooltip)


def dish(id_, n, s, recipe, art, container=None, effects=(), stack=None, tags=(), name=None,
         category="dish", fast=False, always=False, drink=False, count_recipes=None):
    if stack is None:
        stack = 16 if container or drink else 64
    recipes = [recipe] if recipe is not None else []
    if count_recipes:
        recipes += count_recipes
    return ItemDef(id=id_, name=name, food=Food(n, s, always=always or drink, fast=fast, effects=list(effects)),
                   container=container, drink=drink, stack=stack, recipes=recipes, art=art, tags=list(tags),
                   tab="kitchen", category=category)


def drink(id_, n, s, recipe, art, container=BOTTLE, effects=(), tags=("c:drinks",), name=None):
    return dish(id_, n, s, recipe, art, container=container, effects=effects, tags=tags, name=name,
                category="drink", drink=True)


